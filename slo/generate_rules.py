"""Generate Prometheus recording + multi-window, multi-burn-rate alert rules.

    python -m slo.generate_rules          # write monitoring/rules/slo-rules.yml
    python -m slo.generate_rules --check  # CI: fail if the file is stale

Alerting follows the Google SRE Workbook ("Alerting on SLOs"): an alert fires
only when both a long and a short window exceed the burn-rate threshold, which
gives fast detection for big outages, low noise, and quick reset after recovery.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

from slo.budget import DEFAULT_CONFIG, load_config, render

OUTPUT = Path(__file__).resolve().parent.parent / "monitoring" / "rules" / "slo-rules.yml"
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]

# (severity, [(long window, short window, burn-rate factor), ...], for)
# 14.4x for 1h = 2% of a 30d budget gone in an hour -> wake someone up.
# 1x for 3d = on track to spend the whole budget -> ticket for business hours.
BURN_POLICIES = [
    ("page", [("1h", "5m", 14.4), ("6h", "30m", 6)], "2m"),
    ("ticket", [("1d", "2h", 3), ("3d", "6h", 1)], "15m"),
]
HEADER = "# GENERATED by slo/generate_rules.py from slo/slos.yaml - do not edit by hand.\n"


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True  # no &id001 anchors: keep the output readable


def _str_presenter(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_presenter)


def error_ratio_expr(slo: dict, window: str) -> str:
    total = render(slo["total_query"], window)
    if "bad_query" in slo:
        return f"(\n  {render(slo['bad_query'], window)}\n)\n/\n{total}\n"
    good = render(slo["good_query"], window)
    return f"1 - (\n  {good}\n  /\n  {total}\n)\n"


def build(config: dict) -> dict:
    service = config["service"]
    groups = []
    for slo in config["slos"]:
        name = slo["name"]
        budget = round(1 - slo["objective"], 6)
        labels = {"service": service, "slo": name}
        selector = f'{{service="{service}",slo="{name}"}}'

        recording = [
            {"record": f"slo:sli_error:ratio_rate{w}", "expr": error_ratio_expr(slo, w), "labels": labels}
            for w in WINDOWS
        ]
        recording.append({"record": "slo:objective:ratio", "expr": f"vector({slo['objective']})", "labels": labels})
        recording.append({"record": "slo:error_budget:ratio", "expr": f"vector({budget})", "labels": labels})

        alerts = []
        for severity, pairs, for_ in BURN_POLICIES:
            clauses = []
            for long_w, short_w, factor in pairs:
                threshold = round(factor * budget, 6)
                clauses.append(
                    "(\n"
                    f"  slo:sli_error:ratio_rate{long_w}{selector} > {threshold}\n"
                    "  and\n"
                    f"  slo:sli_error:ratio_rate{short_w}{selector} > {threshold}\n"
                    ")"
                )
            speed = "FastBurn" if severity == "page" else "SlowBurn"
            alerts.append({
                "alert": f"{service.title().replace('-', '')}{name.title()}{speed}",
                "expr": "\nor\n".join(clauses) + "\n",
                "for": for_,
                "labels": {"severity": severity, **labels},
                "annotations": {
                    "summary": f"{service}: {name} error budget burning too fast ({severity})",
                    "description": (
                        f"SLO {name} ({slo['objective']:.2%}) is consuming error budget faster than "
                        f"the {severity} policy allows. Long-window error ratio: "
                        f"{{{{ $value | humanizePercentage }}}}."
                    ),
                    "runbook_url": f"{config['runbook_base']}#{name}",
                },
            })

        groups.append({"name": f"slo-{name}-recording", "interval": "30s", "rules": recording})
        groups.append({"name": f"slo-{name}-alerts", "rules": alerts})
    return {"groups": groups}


def render_rules(config: dict) -> str:
    return HEADER + yaml.dump(build(config), Dumper=_Dumper, sort_keys=False, width=200)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", default=str(DEFAULT_CONFIG))
    parser.add_argument("--output", default=str(OUTPUT))
    parser.add_argument("--check", action="store_true", help="exit 1 if the output file is out of date")
    args = parser.parse_args(argv)

    content = render_rules(load_config(args.config))
    output = Path(args.output)
    if args.check:
        if not output.exists() or output.read_text() != content:
            print(f"{output} is stale - run `python -m slo.generate_rules`", file=sys.stderr)
            return 1
        print(f"{output} is up to date")
        return 0
    output.write_text(content)
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
